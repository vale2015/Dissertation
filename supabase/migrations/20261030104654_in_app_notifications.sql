-- Private event-driven inbox. The Flask server is the only application reader/writer.
BEGIN;

CREATE TABLE public.in_app_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    event_type text NOT NULL CHECK (event_type IN ('report_saved')),
    source_id bigint NOT NULL CHECK (source_id > 0),
    dedupe_key text NOT NULL UNIQUE CHECK (char_length(dedupe_key) BETWEEN 1 AND 160),
    title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
    body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 500),
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at timestamptz,
    expires_at timestamptz NOT NULL DEFAULT (now() + interval '90 days'),
    CHECK (expires_at > created_at),
    CHECK (read_at IS NULL OR read_at >= created_at)
);

CREATE INDEX in_app_notifications_recipient_recent_idx
    ON public.in_app_notifications (recipient_id, created_at DESC, id DESC);
CREATE INDEX in_app_notifications_unread_idx
    ON public.in_app_notifications (recipient_id) WHERE read_at IS NULL;
CREATE INDEX in_app_notifications_expiry_idx
    ON public.in_app_notifications (expires_at);

ALTER TABLE public.in_app_notifications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.in_app_notifications FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.in_app_notifications_id_seq FROM PUBLIC, anon, authenticated;

COMMIT;
