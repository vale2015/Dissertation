-- Actual served covers are entered after service, never inferred from bookings.
-- Corrections preserve the previous value and the manager's reason.
BEGIN;

CREATE TABLE public.service_actual_covers (
    service_date date PRIMARY KEY,
    actual_covers integer NOT NULL CHECK (actual_covers BETWEEN 0 AND 100000),
    recorded_by bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint REFERENCES public.users(id) ON DELETE RESTRICT,
    updated_at timestamptz
);

CREATE TABLE public.service_actual_corrections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_date date NOT NULL REFERENCES public.service_actual_covers(service_date) ON DELETE RESTRICT,
    previous_covers integer NOT NULL CHECK (previous_covers BETWEEN 0 AND 100000),
    corrected_covers integer NOT NULL CHECK (corrected_covers BETWEEN 0 AND 100000),
    CONSTRAINT service_actual_corrections_changed CHECK (previous_covers <> corrected_covers),
    reason text NOT NULL CHECK (length(btrim(reason)) BETWEEN 5 AND 500),
    corrected_by bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    corrected_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX service_actual_corrections_date_idx
    ON public.service_actual_corrections (service_date, id DESC);
CREATE INDEX service_actual_covers_recorded_by_idx
    ON public.service_actual_covers (recorded_by);
CREATE INDEX service_actual_covers_updated_by_idx
    ON public.service_actual_covers (updated_by) WHERE updated_by IS NOT NULL;
CREATE INDEX service_actual_corrections_corrected_by_idx
    ON public.service_actual_corrections (corrected_by);

CREATE FUNCTION public.reject_service_actual_correction_mutation()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    RAISE EXCEPTION 'Actual-cover correction history is immutable';
END;
$$;
CREATE TRIGGER service_actual_corrections_immutable
    BEFORE UPDATE OR DELETE ON public.service_actual_corrections
    FOR EACH ROW EXECUTE FUNCTION public.reject_service_actual_correction_mutation();
REVOKE ALL ON FUNCTION public.reject_service_actual_correction_mutation()
    FROM PUBLIC, anon, authenticated;

ALTER TABLE public.service_actual_covers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.service_actual_corrections ENABLE ROW LEVEL SECURITY;

-- The app uses a protected Flask endpoint and server-side Postgres connection.
-- Do not expose these records through the Supabase Data API.
REVOKE ALL ON TABLE public.service_actual_covers,
    public.service_actual_corrections FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.service_actual_corrections_id_seq
    FROM PUBLIC, anon, authenticated;

COMMIT;
