-- Immutable, bounded report snapshots. Flask alone reads and writes these
-- records through its server-side PostgreSQL connection.
BEGIN;

CREATE TABLE public.report_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    selected_date date NOT NULL,
    days_ahead smallint NOT NULL CHECK (days_ahead IN (7, 10)),
    forecast_start_date date NOT NULL,
    forecast_end_date date NOT NULL,
    generated_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL DEFAULT (now() + interval '90 days'),
    snapshot jsonb NOT NULL CHECK (jsonb_typeof(snapshot) = 'object'),
    pdf_file bytea NOT NULL CHECK (octet_length(pdf_file) BETWEEN 1 AND 262144),
    csv_file bytea NOT NULL CHECK (octet_length(csv_file) BETWEEN 1 AND 262144),
    CHECK (forecast_end_date >= forecast_start_date),
    CHECK (expires_at > created_at)
);

CREATE INDEX report_history_recent_idx
    ON public.report_history (created_at DESC, id DESC);
CREATE INDEX report_history_expiry_idx
    ON public.report_history (expires_at);

ALTER TABLE public.report_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.report_history FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.report_history_id_seq FROM PUBLIC, anon, authenticated;

COMMIT;
