-- Preserve complete prediction and staffing runs; only the active pointer changes.
BEGIN;

CREATE TABLE public.forecast_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    selected_date date NOT NULL,
    days_ahead smallint NOT NULL CHECK (days_ahead IN (7, 10)),
    model_name text NOT NULL,
    model_version text NOT NULL,
    generated_at timestamptz NOT NULL DEFAULT now(),
    prediction jsonb NOT NULL CHECK (jsonb_typeof(prediction) = 'object')
);

CREATE TABLE public.forecast_run_days (
    run_id bigint NOT NULL REFERENCES public.forecast_runs(id) ON DELETE RESTRICT,
    day_index smallint NOT NULL CHECK (day_index BETWEEN 1 AND 10),
    forecast_date date NOT NULL,
    predicted_covers integer NOT NULL CHECK (predicted_covers >= 0),
    closed boolean NOT NULL,
    PRIMARY KEY (run_id, day_index),
    UNIQUE (run_id, forecast_date),
    CHECK (NOT closed OR predicted_covers = 0)
);

CREATE INDEX forecast_run_days_date_idx
    ON public.forecast_run_days (forecast_date, run_id);

CREATE TABLE public.active_forecast_run (
    singleton_id smallint PRIMARY KEY DEFAULT 1 CHECK (singleton_id = 1),
    run_id bigint NOT NULL REFERENCES public.forecast_runs(id) ON DELETE RESTRICT,
    activated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.staff_cost_forecast
    ADD COLUMN run_id bigint REFERENCES public.forecast_runs(id) ON DELETE RESTRICT;
CREATE INDEX staff_cost_forecast_run_id_idx
    ON public.staff_cost_forecast (run_id, forecast_date);

-- Historical snapshots cannot be changed after insertion. Legacy staffing rows
-- (run_id IS NULL) remain untouched until a separately reviewed migration.
CREATE FUNCTION public.reject_forecast_snapshot_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME <> 'staff_cost_forecast' THEN
        RAISE EXCEPTION 'Forecast snapshots are immutable';
    END IF;
    IF OLD.run_id IS NOT NULL THEN
        RAISE EXCEPTION 'Forecast snapshots are immutable';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        RETURN NEW;
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER immutable_forecast_runs
    BEFORE UPDATE OR DELETE ON public.forecast_runs
    FOR EACH ROW EXECUTE FUNCTION public.reject_forecast_snapshot_mutation();
CREATE TRIGGER immutable_forecast_run_days
    BEFORE UPDATE OR DELETE ON public.forecast_run_days
    FOR EACH ROW EXECUTE FUNCTION public.reject_forecast_snapshot_mutation();
CREATE TRIGGER immutable_staff_cost_forecast_run_rows
    BEFORE UPDATE OR DELETE ON public.staff_cost_forecast
    FOR EACH ROW EXECUTE FUNCTION public.reject_forecast_snapshot_mutation();

ALTER TABLE public.forecast_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.forecast_run_days ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.active_forecast_run ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.forecast_runs, public.forecast_run_days,
    public.active_forecast_run FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.forecast_runs_id_seq FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.reject_forecast_snapshot_mutation()
    FROM PUBLIC, anon, authenticated;

COMMIT;
