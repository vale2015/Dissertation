from flask import Blueprint
from app.controllers.staff_controller import list_controller,roles_controller,detail_controller,register_controller,update_controller,status_controller,reset_controller
from app.middleware.authorization_middleware import require_permission
from app.services.permission_service import MANAGE_STAFF_ACCOUNTS
from app.controllers.staff_chat_controller import lookup_controller,current_controller,create_controller,detail_controller as chat_detail_controller,patch_controller,review_controller,confirm_controller,cancel_controller,model_budget_controller
staff_bp=Blueprint("staff",__name__)
@staff_bp.get("/")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def staff_list():return list_controller()
@staff_bp.get("/roles")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def roles():return roles_controller()
@staff_bp.post("/registrations")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def register():return register_controller()
@staff_bp.post("/<int:user_id>/password-reset")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def reset(user_id):return reset_controller(user_id)
@staff_bp.get("/<int:user_id>")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def detail(user_id):return detail_controller(user_id)
@staff_bp.patch("/<int:user_id>")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def update(user_id):return update_controller(user_id)
@staff_bp.patch("/<int:user_id>/status")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def status(user_id):return status_controller(user_id)
@staff_bp.get("/chat-lookup")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_lookup():return lookup_controller()
@staff_bp.get("/chat-actions/current")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_current():return current_controller()
@staff_bp.post("/chat-actions")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_create():return create_controller()
@staff_bp.get("/chat-actions/<uuid:action_id>")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_detail(action_id):return chat_detail_controller(action_id)
@staff_bp.patch("/chat-actions/<uuid:action_id>")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_patch(action_id):return patch_controller(action_id)
@staff_bp.post("/chat-actions/<uuid:action_id>/review")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_review(action_id):return review_controller(action_id)
@staff_bp.post("/chat-actions/<uuid:action_id>/confirm")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_confirm(action_id):return confirm_controller(action_id)
@staff_bp.delete("/chat-actions/<uuid:action_id>")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_cancel(action_id):return cancel_controller(action_id)
@staff_bp.post("/chat-model-budget")
@require_permission(MANAGE_STAFF_ACCOUNTS)
def chat_model_budget():return model_budget_controller()
